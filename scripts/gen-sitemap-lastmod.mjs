#!/usr/bin/env node
/**
 * Regenerate src/data/sitemap-lastmod.json from git history.
 *
 * Why: sitemap lastmod was a single hand-bumped constant (CONTENT_UPDATED), so it was wrong for
 * every page except the one that was last edited, and it went stale without anyone noticing. Google
 * treats lastmod as a signal only while it is trustworthy, so a wrong one is worse than none.
 *
 * What it does: one `git log -1 --format=%cs -- <file>` per source file that a page group renders,
 * and writes the commit date for each. The sitemap takes the newest date across the files a route
 * depends on and falls back to CONTENT_UPDATED for anything not listed here.
 *
 * Run by `prebuild`, so deploy.sh gets fresh dates; the JSON is committed so a build without git
 * still works. Dates are the commit dates of the content source, not the request date.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(root, "src/data/sitemap-lastmod.json");

/** Source files whose commit date drives a page group's lastmod. Keep in sync with sitemap.xml.ts. */
const FILES = [
  "src/routes/index.tsx",
  "src/routes/shop.tsx",
  "src/routes/about.tsx",
  "src/routes/calculator.tsx",
  "src/routes/contact.tsx",
  "src/routes/cookies.tsx",
  "src/routes/faq.tsx",
  "src/routes/lab-reports.tsx",
  "src/routes/privacy.tsx",
  "src/routes/research-use-policy.tsx",
  "src/routes/returns.tsx",
  "src/routes/shipping.tsx",
  "src/routes/terms.tsx",
  "src/routes/guides.index.tsx",
  "src/routes/guides.$slug.tsx",
  "src/routes/category.$slug.tsx",
  "src/routes/collections.$slug.tsx",
  "src/routes/product.$slug.tsx",
  "src/data/categories.ts",
  "src/data/category-content.ts",
  "src/data/shop-sections.ts",
  "src/data/compounds-a.ts",
  "src/data/compounds-b.ts",
  "src/data/coa.ts",
  "src/lib/catalog.ts",
  "src/lib/pdp-schema.ts",
];

const gitDate = (file) => {
  try {
    const out = execFileSync("git", ["log", "-1", "--format=%cs", "--", file], {
      cwd: root,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
    return /^\d{4}-\d{2}-\d{2}$/.test(out) ? out : null;
  } catch {
    return null;
  }
};

const files = {};
for (const f of FILES) {
  const d = gitDate(f);
  if (d) files[f] = d;
}

const payload = {
  // Generated by scripts/gen-sitemap-lastmod.mjs. Do not edit by hand.
  generated: new Date().toISOString().slice(0, 10),
  files,
};

writeFileSync(OUT, `${JSON.stringify(payload, null, 2)}\n`);
console.log(`sitemap-lastmod: ${Object.keys(files).length}/${FILES.length} files dated -> ${OUT}`);
