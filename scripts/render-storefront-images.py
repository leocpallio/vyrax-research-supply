"""Derive batch-neutral home and social images from the existing Vyrax hero photo.

Run from the repository root: python3 scripts/render-storefront-images.py
Requires Pillow. Source photo is unchanged; no vial label, certificate, batch code,
expiry, purity or testing claim is generated by this script.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "src" / "assets"
SOURCE = ASSETS / "vyrax-hero.jpg"
REGULAR = "/usr/share/fonts/opentype/inter/Inter-Regular.otf"
SEMIBOLD = "/usr/share/fonts/opentype/inter/Inter-SemiBold.otf"
INK = (23, 36, 57)
WHITE = (255, 255, 255)


def cover(im: Image.Image, size: tuple[int, int]) -> Image.Image:
    width, height = size
    factor = max(width / im.width, height / im.height)
    resized = im.resize((round(im.width * factor), round(im.height * factor)), Image.Resampling.LANCZOS)
    # Preserve the right of the existing lab scene rather than inventing another vial.
    left = resized.width - width
    top = (resized.height - height) // 2
    return resized.crop((left, top, left + width, top + height))


def white_fade(im: Image.Image, start: int, end: int, min_alpha: int = 0) -> Image.Image:
    """Reserve legible white space at left without covering the source subject."""
    overlay = Image.new("RGBA", im.size, (255, 255, 255, 0))
    alpha = Image.new("L", (im.width, 1))
    alpha.putdata([
        255 if x <= start else min_alpha if x >= end
        else round(255 - (255 - min_alpha) * (x - start) / (end - start))
        for x in range(im.width)
    ])
    overlay.putalpha(alpha.resize(im.size))
    return Image.alpha_composite(im.convert("RGBA"), overlay).convert("RGB")


def main() -> None:
    with Image.open(SOURCE) as source:
        source = source.convert("RGB")
        # Wide, copy-safe composition; the page text remains accessible HTML.
        hero = Image.new("RGB", (1920, 1080), WHITE)
        hero.paste(cover(source, (1728, 1080)), (192, 0))
        hero = white_fade(hero, 450, 1240)
        hero.save(ASSETS / "vyrax-hero-wide.webp", "WEBP", quality=86, method=6)

        # Social preview has its own live, machine-readable text and RUO disclosure.
        social = Image.new("RGB", (1200, 630), WHITE)
        social.paste(cover(source, (790, 630)), (410, 0))
        social = white_fade(social, 440, 930)
        draw = ImageDraw.Draw(social)
        small = ImageFont.truetype(SEMIBOLD, 23)
        heading = ImageFont.truetype(SEMIBOLD, 54)
        body = ImageFont.truetype(REGULAR, 24)
        draw.rounded_rectangle((76, 67, 125, 74), radius=3, fill=(67, 112, 137))
        draw.text((76, 94), "VYRAX LABS", font=small, fill=INK)
        draw.text((76, 195), "Research peptides", font=heading, fill=INK)
        draw.text((76, 265), "for laboratory work.", font=heading, fill=INK)
        draw.line((76, 377, 575, 377), fill=(196, 209, 217), width=2)
        draw.text((76, 406), "FOR RESEARCH USE ONLY", font=small, fill=INK)
        draw.text((76, 529), "vyraxlabs.co.uk", font=body, fill=INK)
        social.save(ASSETS / "vyrax-social.webp", "WEBP", quality=88, method=6)


if __name__ == "__main__":
    main()
