#!/usr/bin/env python3
"""Build email thumbnails: src/assets/products/sm/<slug>__<strength>.webp -> public/email-thumbs/<slug>__<strength>.jpg (160px, JPEG; Outlook cannot show WebP).
Run after any render change, then commit public/email-thumbs. Idempotent."""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parent.parent
src = root / "src/assets/products/sm"
out = root / "public/email-thumbs"
out.mkdir(exist_ok=True)
SIZE = 160
n = 0
stems = []
for f in sorted(src.glob("*.webp")):
    if "__" not in f.stem or f.stem.count("__") > 1:
        continue  # front views only
    im = Image.open(f).convert("RGB").resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    im.save(out / f"{f.stem}.jpg", "JPEG", quality=86, optimize=True, progressive=True)
    n += 1
    stems.append(f.stem)
print(f"wrote {n} thumbs to {out}")
(root / "src/lib/email/thumbs.ts").write_text(
    "// GENERATED by scripts/build-email-thumbs.py. Do not edit.\n"
    "const STEMS: readonly string[] = " + __import__("json").dumps(stems) + ";\n"
    "export const hasEmailThumb = (stem: string) => STEMS.includes(stem);\n"
)
print("wrote src/lib/email/thumbs.ts")
